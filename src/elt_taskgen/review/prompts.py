    "prose with ONE rule surgically removed — the null default, the "
    "duplicate-header rule, the scope filter, the row-retention rule, the "
    "item-total rule — and prose left intact while ONE mart column "
    "description is rewritten to contradict a rule that is still there. Only "
    "a finding that actually refers to the missing rule, or names both halves "
    "of the contradiction, counts as a detection.\n"
    "\n"
    "SEVERITY: 'major' when the readings produce different graded outputs; "
    "'fatal' only when "
    "the prose contradicts the mart output schema outright. THERE IS NO "
    "SEVERITY FOR LOOSENESS THAT CANNOT CHANGE GRADED OUTPUT — if the "
