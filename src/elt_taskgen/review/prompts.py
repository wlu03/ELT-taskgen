    "declared measure must have a stated value, and 'is it NULL or 0 here?' "
    "is a real fork worth 'major'. Likewise a source row that lands in the "
    "WRONG named group, or is counted twice inside one, changes a graded "
    "value and is a real fork.\n"
    "  * NO EMPTY GROUP, NO EMPTY-RESULT FORK. 'What does this measure "
    "report when there are no rows?' is only a question when the grain "
    "ADMITS an output row with no matching input rows. It does when the "
    "grain sentence says so — 'one row per customer, including customers "
    "with no orders' — or when a rule retains parents that have no "
    "children. It does NOT when the grain is drawn FROM the very rows "
    "being aggregated (one row per account_id, placement, date_day of the "
    "report table itself), because then every output row has at least one "
    "input row by construction. In that second case there is no empty "
    "group to default, and a measure whose empty-result value is unstated "
