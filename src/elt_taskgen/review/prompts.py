    "computed, or which records a measure counts. A COLUMN NAME IS NOT A "
    "RULE — a column called completed_order_count tells you the column "
    "exists; it does not state which orders count, and if the rules never "
    "say, that IS a graded fork and you must file it. Reading a filter, a "
    "join direction or a denominator out of a column's NAME is the mistake "
    "this rule exists to prevent in the other direction.\n"
    "  * GRAIN IS AUTHORITATIVE OVER ROW MEMBERSHIP. The mart's grain "
    "sentence and key columns settle which rows exist. A source row carrying "
    "no value for a key column — a NULL foreign key, an unmatched child — "
    "belongs to no group the grain names, and its absence from the output is "
    "not a second reading. Never file a fork whose second arm invents an "
    "output row for a key value the grain does not name; the schema "
    "declaring the column nullable is what makes that row unmatched, not "
    "what makes the rule ambiguous. THE RULE CUTS ONE WAY: it bars "
    "inventing rows for key values the grain does not name; it never settles "
    "whether a key value the grain DOES name survives when it has no matching "
    "child rows. 'One row per customer' names the key, not the join: unless a "
    "rule or the grain sentence itself says that customers with no orders in "
    "scope are retained (or excluded), the prose supports both a LEFT JOIN "
    "that keeps them with defaulted measures and an aggregate over orders "
    "that loses them, and that unstated row-retention rule is one of the "
    "removed rules the harness plants — file it at 'major', naming the parent "
    "rows the prose never accounts for. THIS RULE IS ABOUT ROW MEMBERSHIP ONLY "
    "and never excuses the opposite question: for a row the grain DOES name "
