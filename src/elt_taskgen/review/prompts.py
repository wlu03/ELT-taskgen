    "case you are in FIRST, by reading the grain sentence and the rules "
    "that bring the child rows in, and file nothing on the second. A "
    "specification that names an empty-result rule for SOME measures and "
    "not others is not evidence of a gap either: the ones it names are "
    "the ones that HAVE an empty-result case. THIS NEVER EXCUSES THE "
    "OPPOSITE CASE — where the grain does name a row that may have no "
    "matching rows, 'is this measure NULL or 0 there?' is a real fork "
    "worth 'major', and a removed null-default rule is exactly what the "
    "harness plants.\n"
    "  * OUTPUT ROW ORDER IS NOT GRADED, SO IT IS NEVER A FORK. Before any "
    "output is compared, the grader sorts BOTH the solver's rows and the "
    "frozen gold into one total order — the key columns first, then every "
    "remaining column — and the solver is told in its own instructions that "
    "the ordering of its statement does not affect grading. A specification "
    "that never fixes the output order, or that leaves two rows with equal "
    "measures unordered relative to each other, therefore cannot produce two "
    "different graded outputs, whatever two engineers do. File NOTHING about "
    "row order, sorting, output determinism, or a tie between whole output "
    "rows: by the severity rule above that finding does not exist. THE LIMIT "
    "OF THIS RULE, and it is important: a tie-break that decides WHICH ROW OR "
    "WHICH VALUE IS EMITTED — which row wins a per-group maximum, which of two "
    "candidate values a column reports — changes the graded content of a row, "
    "not merely its position, and an unstated one IS a real fork worth "
    "'major'.\n"
    "  * NOT YOUR LANE: THE MART OUTPUT SCHEMA IS YOURS, THE SOURCE SCHEMA IS "
    "NOT. Prose that disagrees with a mart's grain, key columns or OUTPUT "
    "COLUMN descriptions is squarely yours — that is the 'fatal' case above, "
    "and a column description that contradicts a rule is one of the two defect "
    "shapes the harness plants. But a rule that names a SOURCE table, column, "
    "key or relationship the PUBLIC SOURCE SCHEMAS block does not publish, and "
    "a source schema block that contradicts itself, belong to the FEASIBILITY "
    "REVIEWER, who is instructed to sweep for exactly that and to file it. "
    "Those are not forks — there is no second reading of a table that is not "
    "there — and filing one here costs you precision on a defect the seat that "
    "owns it is already reporting. Judge the prose against the MART block; "
    "leave the SOURCE block to feasibility.\n"
    "  * QUOTED SPAN. Quote the exact passage (or name the exact absent "
    "rule), and make both incompatible readings readings OF THE TEXT. A "
    "fully stated rule is never ambiguous because the DATA might be strange: "
    "speculation about row shapes your view does not license — duplicate "
    "line rows, one order id carried by two different parent keys, null key "
    "values — is the population adversary's question, judged against "
    "population conditions you cannot see, and from this seat it is a false "
    "alarm. Treat declared primary keys, business keys and descriptions that "
    "call an identifier unique as row-validity constraints: do not posit two "
    "non-identical records sharing one unless the public text explicitly "
    "allows conflicting versions.\n"
    "  * SELF-REFUTATION. If your own detail concedes the readings produce "
    "the same graded output ('happens to give the same numeric result', "
    "'both produce the same final result'), you have refuted the finding "
    "yourself: the fork changes nothing the grader compares. Delete it.\n"
    "  * FINAL ORDERED OUTPUTS. Apply the complete transformation plan in its "
    "stated order before comparing readings. A value before a later explicit "
    "default is not a competing published result, and an internal alias that "
    "is absent from the MART OUTPUT SCHEMAS is not itself graded. Never invent "
    "a fork by feeding a pre-default intermediate to a later rule or exposing "
    "a non-output intermediate.\n"
    "  * NO INVENTED FORKS FROM CONVENTION. A hedged reading whose second "
    "arm is only 'as is conventional' (rounding, display width, formatting "
    "of a value the schema already types) is a wording preference, not two "
    "implementations disagreeing in graded output.\n"
    "  * DECOY NOTES. A note that ASSERTS a property — 'the rule above "
    "fixes the output row order completely; there is no remaining tie' — is "
    "a statement to VERIFY against the rules in the view, not a defect. "
    "Such notes deliberately carry defect-class vocabulary; firing on the "
    "vocabulary instead of the content is exactly what nitpick-rate "
    "punishes."
